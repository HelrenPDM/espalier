defmodule Espalier.Media.SniffTest do
  @moduledoc """
  Task 0018, steps 5 and 23 (ASVS 5.2.2): `Espalier.Media.Sniff.detect/2`
  takes the kind and the format from the leading bytes, accepts only the
  extensions of that kind (compared in lower case), reads the image size
  from the header before any process runs, answers `too_many_pixels` above
  `max_input_pixels`, tells an APNG from a PNG by the chunk walk and an
  animated WebP by its `VP8X` flag, and rejects HEIF and AVIF `ftyp`
  brands. `webp_info/1` reads the facts of a WebP delivery file.

  The samples are written by hand or generated by ffmpeg from `lavfi`
  sources at test start.
  """
  use ExUnit.Case, async: true

  import Bitwise

  alias Espalier.Media.Sniff

  @moduletag :tmp_dir

  @heif_brands ~w(mif1 mif2 msf1 heic heix heim heis hevc hevx hevm hevs avif avis avio)

  @extensions %{
    image: ~w(png jpg jpeg gif webp),
    svg: ~w(svg),
    video: ~w(mp4 m4v mov webm mkv),
    captions: ~w(vtt)
  }

  describe "signatures" do
    test "every signature passes with every extension of its kind", %{tmp_dir: dir} do
      for {label, bytes, kind, format} <- signatures(),
          ext <- Map.fetch!(@extensions, kind) do
        path = write!(dir, "#{label}.bin", bytes)

        assert {:ok, %{kind: ^kind, format: ^format}} = Sniff.detect(path, "sample.#{ext}"),
               "#{label} as .#{ext}"
      end
    end

    test "the extension is compared in lower case", %{tmp_dir: dir} do
      for {label, bytes, kind, format} <- signatures(),
          ext <- Map.fetch!(@extensions, kind),
          name <- ["SAMPLE.#{String.upcase(ext)}", "Sample.#{String.capitalize(ext)}"] do
        path = write!(dir, "#{label}.bin", bytes)
        assert {:ok, %{kind: ^kind, format: ^format}} = Sniff.detect(path, name), name
      end
    end

    test "only the extension of the file name counts", %{tmp_dir: dir} do
      path = write!(dir, "sample.bin", png(48, 32))

      for name <- ["../../etc/passwd.png", "a b; rm -rf x.png", "dir/sub/x.PNG", "x.tar.png"] do
        assert {:ok, %{format: "png_pipe"}} = Sniff.detect(path, name), name
      end
    end

    test "a file without an extension of its kind answers extension_mismatch", %{tmp_dir: dir} do
      for {label, bytes, kind, _format} <- signatures(),
          {other, exts} <- @extensions,
          other != kind,
          ext <- exts do
        path = write!(dir, "#{label}.bin", bytes)
        assert Sniff.detect(path, "sample.#{ext}") == {:error, :extension_mismatch}, label
      end
    end

    test "an unknown extension answers extension_mismatch", %{tmp_dir: dir} do
      for {label, bytes, _kind, _format} <- signatures(),
          name <-
            ~w(sample.bmp sample.txt sample.m3u8 sample.html sample.png.exe sample .png. heic) do
        path = write!(dir, "#{label}.bin", bytes)
        assert Sniff.detect(path, name) == {:error, :extension_mismatch}, "#{label} as #{name}"
      end
    end

    test "an image signature under another image extension keeps the format of the signature",
         %{tmp_dir: dir} do
      png = write!(dir, "png.bin", png(48, 32))
      gif = write!(dir, "gif.bin", gif("GIF89a", 30, 20))

      assert {:ok, %{format: "png_pipe", width: 48}} = Sniff.detect(png, "photo.jpg")
      assert {:ok, %{format: "gif", width: 30}} = Sniff.detect(gif, "photo.webp")
    end

    test "the detection of the other kinds carries no size", %{tmp_dir: dir} do
      svg = write!(dir, "a.svg", ~s(<svg xmlns="http://www.w3.org/2000/svg"/>))
      vtt = write!(dir, "a.vtt", "WEBVTT\n")
      mp4 = write!(dir, "a.mp4", ftyp("isom", ["isom", "mp41"]))
      mkv = write!(dir, "a.mkv", ebml())

      assert Sniff.detect(svg, "a.svg") ==
               {:ok, %{kind: :svg, format: nil, width: nil, height: nil, animated: false}}

      assert Sniff.detect(vtt, "a.vtt") ==
               {:ok, %{kind: :captions, format: nil, width: nil, height: nil, animated: false}}

      assert Sniff.detect(mp4, "a.mp4") ==
               {:ok, %{kind: :video, format: "mov", width: nil, height: nil, animated: false}}

      assert Sniff.detect(mkv, "a.webm") ==
               {:ok,
                %{kind: :video, format: "matroska", width: nil, height: nil, animated: false}}
    end
  end

  describe "unsupported types" do
    test "a text file named .png", %{tmp_dir: dir} do
      path = write!(dir, "notes.png", "These are plain notes, no image.\n")
      assert Sniff.detect(path, "notes.png") == {:error, :unsupported_type}
    end

    test "an HLS playlist under a video, image or playlist name", %{tmp_dir: dir} do
      path =
        write!(dir, "list", """
        #EXTM3U
        #EXT-X-VERSION:3
        #EXTINF:10.0,
        file:///etc/passwd
        #EXTINF:10.0,
        http://127.0.0.1:9/segment.ts
        #EXT-X-ENDLIST
        """)

      for name <- ~w(clip.mp4 clip.mov clip.webm clip.mkv clip.png clip.m3u8) do
        assert Sniff.detect(path, name) == {:error, :unsupported_type}, name
      end
    end

    test "an ffconcat list", %{tmp_dir: dir} do
      path =
        write!(dir, "list", """
        ffconcat version 1.0
        file 'file:///etc/passwd'
        file 'http://127.0.0.1:9/x.webm'
        """)

      for name <- ~w(clip.mp4 clip.webm clip.mkv) do
        assert Sniff.detect(path, name) == {:error, :unsupported_type}, name
      end
    end

    test "an empty file under every extension", %{tmp_dir: dir} do
      path = write!(dir, "empty", "")

      for {_kind, exts} <- @extensions, ext <- exts do
        assert Sniff.detect(path, "empty.#{ext}") == {:error, :unsupported_type}, ext
      end
    end

    test "a missing file", %{tmp_dir: dir} do
      assert Sniff.detect(Path.join(dir, "absent.png"), "absent.png") ==
               {:error, :unsupported_type}
    end

    test "truncated and foreign headers", %{tmp_dir: dir} do
      cases = [
        {"png signature only", binary_part(png(4, 4), 0, 8), "x.png"},
        {"png without IHDR", <<0x89, "PNG\r\n", 0x1A, "\n">> <> chunk("IDAT", "x"), "x.png"},
        {"jpeg SOI only", <<0xFF, 0xD8, 0xFF>>, "x.jpg"},
        {"gif header only", "GIF89a" <> <<1>>, "x.gif"},
        {"gif87 short", "GIF87a", "x.gif"},
        {"webp without a known chunk", riff_webp(chunk_le("ICCP", "abcd")), "x.webp"},
        {"bmp", "BM" <> :binary.copy(<<0>>, 60), "x.png"},
        {"tiff", "II*\0" <> :binary.copy(<<0>>, 60), "x.jpg"},
        {"short ftyp", <<12::32, "ftyp", "isom">>, "x.mp4"},
        {"html", "<html><body>no svg</body></html>", "x.svg"},
        {"upper-case svg tag", "<SVG></SVG>", "x.svg"},
        {"zip", "PK\x03\x04" <> :binary.copy(<<0>>, 60), "x.webm"}
      ]

      for {label, bytes, name} <- cases do
        path = write!(dir, "case", bytes)
        assert Sniff.detect(path, name) == {:error, :unsupported_type}, label
      end
    end

    test "a zero width or height", %{tmp_dir: dir} do
      cases = [
        {png(0, 10), "x.png"},
        {png(10, 0), "x.png"},
        {gif("GIF89a", 0, 10), "x.gif"},
        {jpeg([sof(0xC0, 10, 0)]), "x.jpg"}
      ]

      for {bytes, name} <- cases do
        path = write!(dir, "case", bytes)
        assert Sniff.detect(path, name) == {:error, :unsupported_type}, name
      end
    end
  end

  describe "header dimensions" do
    test "the PNG IHDR, hand-written and from ffmpeg", %{tmp_dir: dir} do
      path = write!(dir, "a.png", png(321, 123))
      assert {:ok, %{width: 321, height: 123, animated: false}} = Sniff.detect(path, "a.png")

      generated = Path.join(dir, "gen.png")
      ffmpeg!(["-f", "lavfi", "-i", "color=c=navy:s=33x17", "-frames:v", "1", generated])

      assert {:ok, %{format: "png_pipe", width: 33, height: 17}} =
               Sniff.detect(generated, "gen.png")
    end

    test "the GIF logical screen of GIF87a and GIF89a, and from ffmpeg", %{tmp_dir: dir} do
      for version <- ["GIF87a", "GIF89a"] do
        path = write!(dir, "a.gif", gif(version, 300, 200))
        assert {:ok, %{format: "gif", width: 300, height: 200}} = Sniff.detect(path, "a.gif")
      end

      generated = Path.join(dir, "gen.gif")
      ffmpeg!(["-f", "lavfi", "-i", "color=c=olive:s=35x19", "-frames:v", "1", generated])
      assert {:ok, %{width: 35, height: 19}} = Sniff.detect(generated, "gen.gif")
    end

    test "a baseline JPEG of ffmpeg: SOF0 after APP0 and a comment", %{tmp_dir: dir} do
      path = Path.join(dir, "gen.jpg")
      ffmpeg!(["-f", "lavfi", "-i", "color=c=teal:s=33x17", "-frames:v", "1", path])
      bytes = File.read!(path)

      assert <<0xFF, 0xD8, 0xFF, 0xE0, _rest::binary>> = bytes
      assert :binary.match(bytes, <<0xFF, 0xFE>>) != :nomatch
      assert :binary.match(bytes, <<0xFF, 0xC0>>) != :nomatch

      assert {:ok, %{format: "jpeg_pipe", width: 33, height: 17, animated: false}} =
               Sniff.detect(path, "gen.jpg")
    end

    test "a progressive JPEG: SOF2 after APP0 and APP1", %{tmp_dir: dir} do
      path = Path.join(dir, "gen.jpg")
      ffmpeg!(["-f", "lavfi", "-i", "color=c=maroon:s=41x23", "-frames:v", "1", path])
      <<0xFF, 0xD8, rest::binary>> = File.read!(path)

      # Rewrite the SOF0 marker to SOF2 and add an EXIF segment after SOI;
      # only the header is read, so the scan data stays baseline.
      progressive =
        <<0xFF, 0xD8>> <>
          segment(0xE1, "Exif\0\0" <> :binary.copy("e", 400)) <>
          String.replace(rest, <<0xFF, 0xC0, 0x00, 0x11, 0x08>>, <<0xFF, 0xC2, 0x00, 0x11, 0x08>>,
            global: false
          )

      assert :binary.match(progressive, <<0xFF, 0xC2, 0x00, 0x11>>) != :nomatch
      assert :binary.match(progressive, <<0xFF, 0xC0, 0x00, 0x11>>) == :nomatch

      path = write!(dir, "progressive.jpg", progressive)
      assert {:ok, %{width: 41, height: 23}} = Sniff.detect(path, "progressive.jpeg")
    end

    test "every SOFn marker gives the size, DHT, JPG and DAC do not", %{tmp_dir: dir} do
      for marker <- [0xC0, 0xC1, 0xC2, 0xC3, 0xC5, 0xC6, 0xC7, 0xC9, 0xCA, 0xCB, 0xCD, 0xCE, 0xCF] do
        path = write!(dir, "sof.jpg", jpeg([sof(marker, 640, 480)]))
        assert {:ok, %{width: 640, height: 480}} = Sniff.detect(path, "sof.jpg"), inspect(marker)
      end

      # The payload of these segments would read as 4660 by 22136 if the
      # walk took them for a frame header.
      decoy = <<8, 0x56, 0x78, 0x12, 0x34, 0, 0, 0, 0, 0, 0>>

      for marker <- [0xC4, 0xC8, 0xCC] do
        path = write!(dir, "decoy.jpg", jpeg([segment(marker, decoy), sof(0xC0, 64, 32)]))
        assert {:ok, %{width: 64, height: 32}} = Sniff.detect(path, "decoy.jpg"), inspect(marker)
      end
    end

    test "a large APP1 and further APP segments before the SOF", %{tmp_dir: dir} do
      app1 = segment(0xE1, "Exif\0\0" <> :binary.copy("x", 65_000))
      app2 = segment(0xE2, "ICC_PROFILE\0" <> :binary.copy("p", 65_000))
      app13 = segment(0xED, "Photoshop 3.0\0" <> :binary.copy("q", 65_000))

      path = write!(dir, "large.jpg", jpeg([app1, app2, app13, app1, sof(0xC0, 1234, 567)]))
      assert {:ok, %{width: 1234, height: 567}} = Sniff.detect(path, "large.jpg")
    end

    test "fill bytes before a marker are skipped", %{tmp_dir: dir} do
      bytes =
        <<0xFF, 0xD8>> <>
          segment(0xE0, "JFIF\0" <> <<1, 2, 0, 0, 1, 0, 1, 0, 0>>) <>
          <<0xFF, 0xFF, 0xFF>> <> sof(0xC0, 77, 55) <> <<0xFF, 0xD9>>

      path = write!(dir, "fill.jpg", bytes)
      assert {:ok, %{width: 77, height: 55}} = Sniff.detect(path, "fill.jpg")
    end

    test "a JPEG whose SOF lies beyond the first MiB or after SOS answers unsupported_type",
         %{tmp_dir: dir} do
      filler = segment(0xE1, :binary.copy("z", 65_000))
      beyond = jpeg(List.duplicate(filler, 17) ++ [sof(0xC0, 64, 64)])
      assert byte_size(beyond) > 1_048_576

      path = write!(dir, "beyond.jpg", beyond)
      assert Sniff.detect(path, "beyond.jpg") == {:error, :unsupported_type}

      after_sos = <<0xFF, 0xD8>> <> segment(0xDA, <<1, 1, 0, 0, 63, 0>>) <> sof(0xC0, 64, 64)
      path = write!(dir, "sos.jpg", after_sos)
      assert Sniff.detect(path, "sos.jpg") == {:error, :unsupported_type}
    end

    test "WebP VP8, VP8L and VP8X from ffmpeg", %{tmp_dir: dir} do
      lossy = webp!(dir, "lossy.webp", "testsrc2=s=64x48", ["-c:v", "libwebp"])

      lossless =
        webp!(dir, "lossless.webp", "testsrc2=s=64x48", ["-c:v", "libwebp", "-lossless", "1"])

      animated =
        webp!(dir, "animated.webp", "testsrc2=s=48x32:r=5", [
          "-frames:v",
          "3",
          "-c:v",
          "libwebp_anim"
        ])

      assert chunk_type(lossy) == "VP8 "
      assert chunk_type(lossless) == "VP8L"
      assert chunk_type(animated) == "VP8X"

      assert {:ok, %{format: "webp_pipe", width: 64, height: 48, animated: false}} =
               Sniff.detect(lossy, "a.webp")

      assert {:ok, %{format: "webp_pipe", width: 64, height: 48, animated: false}} =
               Sniff.detect(lossless, "a.webp")

      assert {:ok, %{format: "webp_pipe", width: 48, height: 32, animated: true}} =
               Sniff.detect(animated, "a.webp")
    end

    test "hand-written WebP headers: the scale bits of VP8 and the size fields", %{tmp_dir: dir} do
      # VP8: 14 bits of size, the two upper bits are the scale.
      vp8 = riff_webp(vp8_chunk(300 ||| 1 <<< 14, 200 ||| 3 <<< 14))
      path = write!(dir, "vp8.webp", vp8)
      assert {:ok, %{width: 300, height: 200}} = Sniff.detect(path, "vp8.webp")

      path = write!(dir, "vp8l.webp", riff_webp(vp8l_chunk(1000, 700, false)))
      assert {:ok, %{width: 1000, height: 700}} = Sniff.detect(path, "vp8l.webp")

      path = write!(dir, "vp8x.webp", riff_webp(vp8x_chunk(0, 5000, 4000)))
      assert {:ok, %{width: 5000, height: 4000, animated: false}} = Sniff.detect(path, "x.webp")
    end
  end

  describe "pixel limit" do
    test "a small PNG whose IHDR claims 10000 by 10000 answers too_many_pixels", %{tmp_dir: dir} do
      bytes = png(10_000, 10_000)
      assert byte_size(bytes) < 200
      path = write!(dir, "huge.png", bytes)

      assert Sniff.detect(path, "huge.png") == {:error, :too_many_pixels}
    end

    test "width times height equal to max_input_pixels passes, one more fails", %{tmp_dir: dir} do
      path = write!(dir, "edge.png", png(8000, 5000))
      assert {:ok, %{width: 8000, height: 5000}} = Sniff.detect(path, "edge.png")

      path = write!(dir, "over.png", png(40_000_001, 1))
      assert Sniff.detect(path, "over.png") == {:error, :too_many_pixels}
    end

    test "every image format checks the header size", %{tmp_dir: dir} do
      cases = [
        {gif("GIF89a", 65_535, 65_535), "x.gif"},
        {jpeg([sof(0xC2, 65_535, 65_535)]), "x.jpg"},
        {riff_webp(vp8_chunk(16_383, 16_383)), "x.webp"},
        {riff_webp(vp8l_chunk(16_384, 16_384, true)), "x.webp"},
        {riff_webp(vp8x_chunk(0x02, 16_777_216, 16_777_216)), "x.webp"},
        {apng(10_000, 10_000, []), "x.png"}
      ]

      for {bytes, name} <- cases do
        path = write!(dir, "case", bytes)
        assert Sniff.detect(path, name) == {:error, :too_many_pixels}, name
      end
    end
  end

  describe "the PNG chunk walk" do
    test "an APNG whose acTL follows an iCCP chunk is apng", %{tmp_dir: dir} do
      iccp = chunk("iCCP", "profile\0\0" <> :zlib.compress(:binary.copy("icc", 300)))
      path = write!(dir, "a.png", apng(48, 32, [iccp]))

      assert {:ok, %{format: "apng", width: 48, height: 32, animated: false}} =
               Sniff.detect(path, "a.png")
    end

    test "a PNG without acTL, and one with acTL after the first IDAT, is png_pipe",
         %{tmp_dir: dir} do
      path = write!(dir, "plain.png", png(48, 32, [chunk("tEXt", "Comment\0invented")]))
      assert {:ok, %{format: "png_pipe"}} = Sniff.detect(path, "plain.png")

      late =
        png_signature() <>
          ihdr(48, 32) <>
          chunk("IDAT", :zlib.compress(<<0>>)) <> actl(3) <> chunk("IEND", "")

      path = write!(dir, "late.png", late)
      assert {:ok, %{format: "png_pipe"}} = Sniff.detect(path, "late.png")
    end

    test "the APNG and the still PNG of ffmpeg", %{tmp_dir: dir} do
      apng = Path.join(dir, "anim.png")

      ffmpeg!([
        "-f",
        "lavfi",
        "-i",
        "testsrc2=s=48x32:r=5",
        "-frames:v",
        "3",
        "-plays",
        "0",
        "-f",
        "apng",
        apng
      ])

      still = Path.join(dir, "still.png")
      ffmpeg!(["-f", "lavfi", "-i", "testsrc2=s=48x32", "-frames:v", "1", still])

      assert {:ok, %{format: "apng", width: 48, height: 32}} = Sniff.detect(apng, "anim.png")

      assert {:ok, %{format: "png_pipe", width: 48, height: 32}} =
               Sniff.detect(still, "still.png")
    end

    test "the walk stops after 64 chunks and at 1 MiB", %{tmp_dir: dir} do
      text = chunk("tEXt", "k\0v")
      path = write!(dir, "many.png", apng(48, 32, List.duplicate(text, 70)))
      assert {:ok, %{format: "png_pipe"}} = Sniff.detect(path, "many.png")

      path = write!(dir, "few.png", apng(48, 32, List.duplicate(text, 60)))
      assert {:ok, %{format: "apng"}} = Sniff.detect(path, "few.png")

      big = chunk("zTXt", :binary.copy("b", 1_100_000))
      path = write!(dir, "far.png", apng(48, 32, [big]))
      assert {:ok, %{format: "png_pipe"}} = Sniff.detect(path, "far.png")
    end

    test "a chunk length above 2^31 - 1 answers unsupported_type", %{tmp_dir: dir} do
      for length <- [0x80000000, 0xFFFFFFFF] do
        bytes =
          png_signature() <> ihdr(48, 32) <> <<length::32, "tEXt", "data">> <> chunk("IEND", "")

        path = write!(dir, "long.png", bytes)
        assert Sniff.detect(path, "long.png") == {:error, :unsupported_type}, inspect(length)
      end

      # 2^31 - 1 itself is allowed; the walk then ends outside the window.
      bytes =
        png_signature() <> ihdr(48, 32) <> <<0x7FFFFFFF::32, "tEXt", "data">> <> chunk("IEND", "")

      path = write!(dir, "max.png", bytes)
      assert {:ok, %{format: "png_pipe"}} = Sniff.detect(path, "max.png")
    end
  end

  describe "WebP animation" do
    test "the animation flag of VP8X marks an animated WebP", %{tmp_dir: dir} do
      path = write!(dir, "anim.webp", riff_webp(vp8x_chunk(0x02, 64, 64)))
      assert {:ok, %{animated: true, width: 64, height: 64}} = Sniff.detect(path, "anim.webp")

      # Alpha, EXIF, XMP and ICC flags without the animation bit.
      path =
        write!(dir, "still.webp", riff_webp(vp8x_chunk(0x10 ||| 0x08 ||| 0x04 ||| 0x20, 64, 64)))

      assert {:ok, %{animated: false}} = Sniff.detect(path, "still.webp")
    end
  end

  describe "HEIF and AVIF brands" do
    test "each brand as the major brand answers unsupported_type", %{tmp_dir: dir} do
      for brand <- @heif_brands, ext <- ~w(mp4 m4v mov) do
        path = write!(dir, "heif", ftyp(brand, ["isom", "mp41"]))
        assert Sniff.detect(path, "photo.#{ext}") == {:error, :unsupported_type}, brand
      end
