    test "each brand as a compatible brand next to the major isom answers unsupported_type",
         %{tmp_dir: dir} do
      for brand <- @heif_brands, position <- [0, 1, 4] do
        compatible = List.insert_at(["isom", "iso2", "mp41", "avc1", "dash"], position, brand)
        path = write!(dir, "heif", ftyp("isom", compatible))
        assert Sniff.detect(path, "photo.mp4") == {:error, :unsupported_type}, brand
      end
    end

    test "isom, mp42 and qt pass as mov", %{tmp_dir: dir} do
      for major <- ["isom", "mp42", "qt  ", "M4V ", "iso5"] do
        path = write!(dir, "video", ftyp(major, ["isom", "mp42", "qt  "]))
        assert {:ok, %{kind: :video, format: "mov"}} = Sniff.detect(path, "clip.mov"), major
      end
    end

    test "a real MP4 of ffmpeg passes as mov", %{tmp_dir: dir} do
      path = Path.join(dir, "clip.mp4")

      ffmpeg!([
        "-f",
        "lavfi",
        "-i",
        "testsrc2=s=64x48:r=5",
        "-t",
        "1",
        "-c:v",
        "mpeg4",
        path
      ])

      assert {:ok, %{kind: :video, format: "mov"}} = Sniff.detect(path, "clip.m4v")
    end

    test "only the brands of the ftyp box within the first 64 bytes count", %{tmp_dir: dir} do
      # A brand in the box after ftyp is no brand.
      outside = ftyp("isom", ["isom"]) <> <<16::32, "free", "mif1heic">>
      path = write!(dir, "outside", outside)
      assert {:ok, %{format: "mov"}} = Sniff.detect(path, "clip.mp4")

      # A brand at byte 64 and later lies outside the head.
      far = ftyp("isom", List.duplicate("iso2", 12) ++ ["heic"])
      assert byte_size(far) > 64
      path = write!(dir, "far", far)
      assert {:ok, %{format: "mov"}} = Sniff.detect(path, "clip.mp4")
    end

    test "an ftyp box of size 0 with a HEIF compatible brand answers unsupported_type",
         %{tmp_dir: dir} do
      bytes = <<0::32, "ftyp", "isom", 0::32, "isom", "mif1", "heic">>
      path = write!(dir, "zero", bytes)
      assert Sniff.detect(path, "photo.mp4") == {:error, :unsupported_type}
    end

    test "an ftyp box with a largesize and the major brand heic answers unsupported_type",
         %{tmp_dir: dir} do
      bytes = <<1::32, "ftyp", 32::64, "heic", 0::32, "mif1", "heic">>
      path = write!(dir, "large", bytes)
      assert Sniff.detect(path, "photo.mp4") == {:error, :unsupported_type}
    end
  end

  describe "SVG" do
    test "the three starts, with a BOM and leading white space", %{tmp_dir: dir} do
