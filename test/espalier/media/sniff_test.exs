  defp png_signature, do: <<0x89, "PNG", 0x0D, 0x0A, 0x1A, 0x0A>>

  defp chunk(type, data),
    do: <<byte_size(data)::32, type::binary, data::binary, :erlang.crc32(type <> data)::32>>

  defp ihdr(width, height), do: chunk("IHDR", <<width::32, height::32, 8, 2, 0, 0, 0>>)

  defp actl(frames), do: chunk("acTL", <<frames::32, 0::32>>)

  defp png(width, height, chunks \\ []) do
    png_signature() <>
      ihdr(width, height) <>
      IO.iodata_to_binary(chunks) <>
      chunk("IDAT", :zlib.compress(:binary.copy(<<0>>, 16))) <> chunk("IEND", "")
  end

  defp apng(width, height, before) do
    png(width, height, before ++ [actl(3)])
  end

  defp gif(version, width, height) do
    version <> <<width::little-16, height::little-16, 0, 0, 0>> <> ";"
  end

  defp segment(marker, payload), do: <<0xFF, marker, byte_size(payload) + 2::16, payload::binary>>

  defp sof(marker, width, height) do
    segment(marker, <<8, height::16, width::16, 3, 1, 0x22, 0, 2, 0x11, 1, 3, 0x11, 1>>)
  end

  defp jpeg(segments) do
    <<0xFF, 0xD8>> <>
      segment(0xE0, "JFIF\0" <> <<1, 2, 0, 0, 1, 0, 1, 0, 0>>) <>
      IO.iodata_to_binary(segments) <>
      segment(0xDA, <<1, 1, 0, 0, 63, 0>>) <> <<0x12, 0x34, 0xFF, 0xD9>>
  end

  defp chunk_le(type, data) do
    padding = if rem(byte_size(data), 2) == 1, do: <<0>>, else: <<>>
    <<type::binary, byte_size(data)::little-32, data::binary, padding::binary>>
  end

  defp riff_webp(chunks), do: <<"RIFF", byte_size(chunks) + 4::little-32, "WEBP", chunks::binary>>

  defp vp8_chunk(width_field, height_field) do
    chunk_le(
      "VP8 ",
      <<0x50, 0x03, 0x00, 0x9D, 0x01, 0x2A, width_field::little-16, height_field::little-16,
        0::64>>
    )
  end

  defp vp8l_chunk(width, height, alpha) do
    bits = width - 1 ||| (height - 1) <<< 14 ||| if(alpha, do: 1, else: 0) <<< 28
    chunk_le("VP8L", <<0x2F, bits::little-32, 0::32>>)
  end

  defp vp8x_chunk(flags, width, height) do
    chunk_le("VP8X", <<flags, 0, 0, 0, width - 1::little-24, height - 1::little-24>>)
  end

  defp ftyp(major, compatible) do
    brands = IO.iodata_to_binary(compatible)
    <<16 + byte_size(brands)::32, "ftyp", major::binary, 0x200::32, brands::binary>>
  end

  defp ebml do
    <<0x1A, 0x45, 0xDF, 0xA3, 0x9F, 0x42, 0x86, 0x81, 0x01, 0x42, 0xF7, 0x81, 0x01, 0x42, 0x82,
      0x84, "webm", 0::64>>
  end

  ## Files

  defp write!(dir, name, bytes) do
    path = Path.join(dir, name)
    File.write!(path, bytes)
    path
  end

  defp webp!(dir, name, source, codec) do
    path = Path.join(dir, name)
    frames = if "-frames:v" in codec, do: [], else: ["-frames:v", "1"]
    ffmpeg!(["-f", "lavfi", "-i", source] ++ frames ++ codec ++ [path])
    path
  end

  defp chunk_type(path) do
    <<"RIFF", _size::binary-size(4), "WEBP", type::binary-size(4), _rest::binary>> =
      File.read!(path)

    type
  end

  defp ffmpeg!(args) do
    ffmpeg = System.find_executable("ffmpeg") || flunk("ffmpeg is not on the PATH")

    {output, status} =
      System.cmd(ffmpeg, ["-nostdin", "-hide_banner", "-loglevel", "error", "-y" | args],
        stderr_to_stdout: true
      )

    assert status == 0, output
  end
