  describe "webp_info/1" do
    test "the facts of the three WebP kinds of ffmpeg", %{tmp_dir: dir} do
      lossy = webp!(dir, "lossy.webp", "testsrc2=s=64x48", ["-c:v", "libwebp"])

      lossy_alpha =
        webp!(dir, "lossy-alpha.webp", "color=c=red@0.5:s=32x24,format=yuva420p", [
          "-c:v",
          "libwebp"
        ])

      lossless =
        webp!(dir, "lossless.webp", "testsrc2=s=64x48", ["-c:v", "libwebp", "-lossless", "1"])

      lossless_alpha =
        webp!(dir, "lossless-alpha.webp", "color=c=red@0.5:s=32x24,format=rgba", [
          "-c:v",
          "libwebp",
          "-lossless",
          "1"
        ])

      animated =
        webp!(dir, "animated.webp", "testsrc2=s=48x32:r=5", [
          "-frames:v",
          "3",
          "-c:v",
          "libwebp_anim"
        ])

      assert chunk_type(lossy_alpha) == "VP8X"

      assert Sniff.webp_info(lossy) ==
               {:ok, %{width: 64, height: 48, has_alpha: false, lossless: false, animated: false}}

      assert Sniff.webp_info(lossy_alpha) ==
               {:ok, %{width: 32, height: 24, has_alpha: true, lossless: false, animated: false}}

      assert Sniff.webp_info(lossless) ==
               {:ok, %{width: 64, height: 48, has_alpha: false, lossless: true, animated: false}}

      assert Sniff.webp_info(lossless_alpha) ==
               {:ok, %{width: 32, height: 24, has_alpha: true, lossless: true, animated: false}}

      assert {:ok, %{width: 48, height: 32, animated: true}} = Sniff.webp_info(animated)
    end

    test "the alpha bit of VP8L, an ALPH chunk after ICCP, and VP8L inside VP8X",
         %{tmp_dir: dir} do
      path = write!(dir, "a.webp", riff_webp(vp8l_chunk(10, 20, true)))

      assert Sniff.webp_info(path) ==
               {:ok, %{width: 10, height: 20, has_alpha: true, lossless: true, animated: false}}

      path = write!(dir, "b.webp", riff_webp(vp8l_chunk(10, 20, false)))
      assert {:ok, %{has_alpha: false, lossless: true}} = Sniff.webp_info(path)

      iccp_alpha =
        vp8x_chunk(0x30, 40, 30) <>
          chunk_le("ICCP", :binary.copy("c", 501)) <>
          chunk_le("ALPH", <<0, 1, 2>>) <> vp8_chunk(40, 30)

      path = write!(dir, "c.webp", riff_webp(iccp_alpha))

      assert Sniff.webp_info(path) ==
               {:ok, %{width: 40, height: 30, has_alpha: true, lossless: false, animated: false}}

      path = write!(dir, "d.webp", riff_webp(vp8x_chunk(0, 40, 30) <> vp8l_chunk(40, 30, false)))
      assert {:ok, %{width: 40, height: 30, lossless: true}} = Sniff.webp_info(path)

      path = write!(dir, "e.webp", riff_webp(vp8x_chunk(0, 40, 30) <> vp8_chunk(40, 30)))
      assert {:ok, %{has_alpha: false, lossless: false}} = Sniff.webp_info(path)
    end

    test "a file that is no WebP, and a missing file, answer :error", %{tmp_dir: dir} do
      assert Sniff.webp_info(write!(dir, "a.png", png(4, 4))) == :error
      assert Sniff.webp_info(write!(dir, "short.webp", "RIFF\0\0\0\0WEBP")) == :error
      assert Sniff.webp_info(Path.join(dir, "absent.webp")) == :error
    end
  end

